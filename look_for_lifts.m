function LoadForm(d,p,lvl_label, evals : HeckeBd := 30)
    // Helper function to load form from value of d, p, the level label, and eigenvalues evals
    // WARNING: this recomputes eigenforms, so it's expensive - it's better to use something else
    F := QuadFld(d);
    lvl := LMFDBIdeal(F, lvl_label);
    W := BianchiWeight(F, 0,0 : char := p);
    B := BianchiCohomologySpace(lvl, W);
    form := 0;
    good_primes := GoodHeckePrimes(B, HeckeBd);
    SetHeckeBound(B, HeckeBd);
    len := Min(#good_primes, #evals);
    // if Dimension(B) eq 1 then
    // 	form := Basis(B)[1];
    // 	form`isEigenform := true;
    // 	return form;
    // end if;
    for f in Eigenforms(B) do
	found := false;
	for i -> ev in evals[1..len] do
	    if ev ne 0 and ev ne EigenvalueList(f)[i] then 
		break;
	    end if;
	end for;
	form := f;
	break;
    end for;
    
    if Type(form) eq Type(0) then
	return "Eigenform not found";
    else
	return form;
    end if;
end function;


function FindLifts(f : lvlLowerBd := 0, lvlBd := 1000000 , at_p := false, includeLvl := false)
    LR_nums := LevelRaiseFactors(f, Min(Floor(lvlBd/Norm(Level(f))), 4000));
    // LR_nums := LevelRaisingPrimes(f);
    // LR_nums cat:= [P[1] : P in Factorization(Parent(f)`level * Characteristic(Parent(f)))];

    if #LR_nums eq 0 then
	return "No level raising primes available";
    else
	print "Level raise factors are", [LMFDBLabel(I) : I in LR_nums];
    end if;
    
    B := Parent(f);
    level1 := Level(B);
    ZZx<x> := PolynomialRing(Integers());
    K<Kgen> := NumberField(B);
    _, levelgen := IsPrincipal(level1);
    print "Level generated by", K!levelgen, "where Kgen satisfies", MinimalPolynomial(Kgen);

    ZK := Integers(K);
    Wp := Weight(B);
    W0 := BianchiWeight(K, 0,0);
    p := Characteristic(B);
    // Only check at primes above p
    if at_p then
	LR_nums := [];
	for fac in Factorization(p*ZK) do
	    Append(~LR_nums, fac[1]);
	    Append(~LR_nums, fac[1]^2);
	end for;
	LR_nums := SortByLMFDBLabel(LR_nums);
    end if;
    
    if includeLvl then
	Append(~LR_nums, 1*ZK);
	LR_nums := SortByLMFDBLabel(LR_nums);
    end if;

    HeckeField := HeckeField(f);
    
    // Caching is supposed to speed this up by storing oldspaces
    // see https://magma.maths.usyd.edu.au/magma/handbook/text/1784#20376
    SetStoreModularForms(K, true);
    // print "Factors are", [LMFDBLabel(I) : I in LR_nums];
    for I in LR_nums do
	level2 := I*level1;
	if Norm(level2) gt lvlBd or Norm(level2) lt lvlLowerBd then
	    print "Skipping level", LMFDBLabel(I), "since not in range specified by lvlLowerBd and lvlBd";
	    continue;
	end if;
	_, princ := IsPrincipal(I);
	print "Looking for lifts with level", LMFDBLabel(I), "=", K!princ, "added; new level is", LMFDBLabel(level2);
	// print "Can kill lifting obstruction?", CanKillLiftingObstr(p, level2,level1);
	// B0 := BianchiCohomologySpace(level2, W0);
	// Bp := BianchiCohomologySpace(level2, Wp);
	// red_map := ReductionModPMap(B0,Bp);
	// reduction := [Bp`down(red_map((Inverse(B0`down)(v)))) : v in Basis(B0`forms)];
	// oldspace := DegenerateSubspace(f, Bp);
        // inter := sub<Bp`forms | reduction> meet oldspace;

	// if Dimension(inter) gt 0 then
	//     print "Found intersection of oldspace and reduction mod p in level", LMFDBLabel(level2);
	// end if;
	primes := SortByLMFDBLabel(Setseq(Keys(Eigenvalues(f))));
	primes := [qq : qq in primes | IsCoprime(qq,level2)];
	C := BianchiCuspForms(K, level2);
	if Dimension(C) eq 0 then
	    print "Characteristic 0 space empty";
	end if;
	print "Computing eigenforms, this may take time";
	
	for j -> F in NewformDecomposition(NewSubspace(C)) do
	    print "Testing eigenform", j;
	    // Compute first Hecke eigenvalue to find field
	    E := Parent(HeckeEigenvalue(Eigenform(F), primes[1]));
	    if Degree(E) gt 1 then
		E<z> := Parent(HeckeEigenvalue(Eigenform(F), primes[1]));
	    else
		z := Rationals()!1;
	    end if;
	    
	    if Degree(E) lt Degree(HeckeField) then
		print "Degree of char 0 eigenvalue field is too small";
		continue;
	    end if;
	    
	    print "Eigenvalues of char 0 lift lie in", E, "of discriminant", Discriminant(Integers(E));
	    p_primes := [m[1] : m in Factorization(p*Integers(E))];
	    
	    for pp in p_primes do
		flag, prin := IsPrincipal(pp);
		Emodp_bad, phi_bad := ResidueClassField(pp);
		if flag then
		    print "Looking at reduction modulo", E!prin, "of residue degree", Degree(Emodp_bad);
		else
		    print "Looking at reduction modulo non-principal ideal above", p;
		end if;
		
		// Get better presentation of finite field than the default one:
		if Degree(Emodp_bad) gt 1 then
		    Fpx := PolynomialRing(GF(p));
		    if not exists(EmodpPol){ fac[1] : fac in Factorization(Fpx!MinimalPolynomial(z)) | Degree(fac[1]) eq Degree(Emodp_bad)} then
			print "Minimal polynomial does not have factor of correct size", [Degree(fac[1]) : fac in Factorization(Fpx!MinimalPolynomial(z))];
			continue;
		    end if;
		    Emodp<w> := ext<GF(p) | EmodpPol>;
		    assert #Emodp eq #Emodp_bad;
		    flag, Eiso := IsIsomorphic(Emodp_bad, Emodp);
		    phi := phi_bad*Eiso;
		    SetPowerPrinting(Emodp, false);
		else
		    EmodpPol := "x-1";
		    Emodp := Emodp_bad;
		    phi := phi_bad;
		end if;

		if Degree(Emodp) eq Degree(HeckeField) then
		    // this is chosen at random goddammit
		    flag, emb := IsIsomorphic(HeckeField, Emodp);
		    assert flag;
		    _, auts, _ := AutomorphismGroup(Emodp);
		elif Degree(Emodp) mod Degree(HeckeField) eq 0 then
		    Embed(HeckeField, Emodp);
		    emb := hom<HeckeField -> Emodp | x :-> Emodp!x>;
		    _, auts, _ := AutomorphismGroup(Emodp);
		else
		    print "Wrong residue degree of prime";
		    continue;
		end if;
		
		// Need to loop over automorphisms because iso is chosen at random
		for aut_no -> aut in auts do
		    wrong_ctr := 0;
		    is_wrong := false;
		    print "Testing automorphism", aut_no;
		    i := emb*aut;
		    for qq in primes do
			_, qq_gen := IsPrincipal(qq);
			
			if i(Eigenvalue(f,qq)) ne phi(HeckeEigenvalue(Eigenform(F), qq)) then
			    // This is not the right one, so move on to another level raising prime;
			    // but we will allow a couple of mismatches just in case.
			    wrong_ctr +:= 1;
			    print "Hecke eigenvalues don't agree for", LMFDBLabel(qq);
			    
			    if wrong_ctr gt 5 then
				is_wrong := true;
				wrong_ctr := 0;
				print "Eigenvalues didn't match, moving to next";
				continue aut;
			    end if;
			else
			    print "Hecke eigenvalues agree for", LMFDBLabel(qq);
			end if;
		    end for;
		    if not is_wrong then 
			print "Found correct form!";
			printf "Using prime above %o corresponding to mod p factor %o of minimal polynomial %o\n", p, EmodpPol, MinimalPolynomial(z);
			colNum := #primes;
			labels := ["$\\mathfrak{p}$"] cat [Sprint(LMFDBLabel(pp)) : pp in primes[1..colNum]];
			fp_evals := ["$a_{\\mathfrak{p}}(f)$"] cat ListToEquationStrings([i(Eigenvalue(f,pp)) : pp in primes[1..colNum]]);
			Fp_evals := ["$a_{\\mathfrak{p}}(F) \\mod p$"] cat ListToEquationStrings([phi(HeckeEigenvalue(Eigenform(F),pp)) : pp in primes[1..colNum]]); 
			F_evals := ["$a_{\\mathfrak{p}}(F)$"] cat ListToEquationStrings([HeckeEigenvalue(Eigenform(F),pp) : pp in primes[1..colNum]]);
			print ListsToLatexTable([labels,fp_evals,Fp_evals, F_evals]);
			return F;
		    end if;

		end for;
	    end for;
	end for;
	print "---\n";
	// return inter;

    end for;
    return "None found";
end function;



/*
Attempts to find lifts of Bianchi cohomology class with irrational coefficients which is given as a string in the format

127.1;7;[ 1, 4 ];[ 1, 2 ];[ 5, 2 ];[ 5, 2 ];[ 0, 3 ];x^2 + 6*x + 3

where 
- the first entry is the level
- the second is the prime p,
- the last entry is the characteristic polynomial of the extension in which the Hecke eigenvalues lie
- the rest of the entries correspond to Hecke eigenvalues
*/

function BatchFindIrrationalLifts(d : lvlBd := 100)
    F := QuadFld(d);
    filename := "data/nonEis_d" cat Sprint(d) cat ".csv";
    lines := Split(Read(filename), "\n");
    header := Split(lines[1], ";");
    primeLabels := header[3..#header-1];
    primeList := [LMFDBIdeal(F,label) : label in primeLabels];

    for line in lines[2..#lines] do
	entries := Split(line, ";");
	if "x" notin entries[#entries] or forall{ 1 : e in entries[3..#entries-1] | "[" notin e} then
	    continue;
	end if;

	lvl := LMFDBIdeal(F, entries[1]);
	p := StringToInteger(entries[2]);
	// skip small primes
	if p eq 2 then continue; end if;
	
	B := BianchiCohomologySpace(lvl, BianchiWeight(F,0,0 : char :=p));
	f := ReadClass(line, B, primeList);
	print "Finding lifts for", f, "; this may take time";
	f0 := FindLifts(f : lvlBd := lvlBd, at_p := true);
	if Type(f0) eq Type("Foo") then
	    print f0;
	    // print "++++FOUND LIFT++++", f0;
	end if;
    end for;
    return 0;
end function;


