function LoadAllLifts(d : startBd := 0, stopBd := 1000)
    F := QuadFld(d);
    filename := "data/nonEis_d" cat Sprint(d) cat ".csv";
    lines := Split(Read(filename), "\n");
    header := Split(lines[1], ";");
    primeLabels := header[3..#header];
    primeList := [LMFDBIdeal(F,label) : label in primeLabels];
    forms := [* *];
    for i -> line in lines[2..#lines] do
	if i le startBd or i gt stopBd then continue; end if;

	entries := Split(line, ";");
	if "x" in entries[#entries] or "[" in entries[3] or exists{true : entry in entries | "w" in entry} then
	    continue;
	end if;

	lvl := LMFDBIdeal(F, entries[1]);
	p := StringToInteger(entries[2]);
	if p in [2,3] then continue; end if;

	B := BianchiCohomologySpace(lvl, BianchiWeight(F,0,0 : char :=p));
	f := ReadClass(line,B, primeList);
	Append(~forms,f);
    end for;
    return forms;
    
end function;


// Check whether p divides the index of Gamma0(J) in Gamma0(I).
// Heuristically, this is expected if the H^2 degeneracy map
// kills the lifting obstruction 
// NOTE: not sure if this is correct; in any case it seems to always return false, so WIP
function CanKillLiftingObstr(p, I,J)
    assert I subset J;
    primes := [pp : pp in Divisors(J) | IsPrime(pp) and IsCoprime(I,pp)];
    if primes ne [] then
	return Norm(J)/Norm(I)* &*primes subset Parent(I)!p;
    else
	return false;
    end if;
end function;

function CheckNonrationalLift(d, line, topLine: extended := false)
    F := QuadFld(d);
    lvl := Split(line, ";")[1];
    topList := Split(topLine, ";");
    primeList := topList[3..#topList];
    p := StringToInteger(Split(line, ";")[2]);
    B := BianchiCohomologySpace(LMFDBIdeal(F, lvl), BianchiWeight(F,0,0 : char := p));
    print "Initializing class from line";
    f := ReadClass(line, B, [LMFDBIdeal(F, I) : I in primeList]);
    print "Initialized class; looking for lifts";
    if not extended then
	return FindLifts(f);
    end if;
    
    fLift := FindLifts(f);

    newLvl := Level(fLift);
    B := BianchiCohomologySpace(newLvl, BianchiWeight(BaseField(fLift),0,0 : char := p));
    SetHeckeBound(B, 50);
    efs := Eigenforms(B);
    print "Exists multiplicity 2 mod p eigenspace of this level?", exists{ef : ef in efs | ef`eigenspaceDim eq 2};
    return fLift;
    
end function;

