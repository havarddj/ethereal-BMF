function FindLifts(f : lvlLowerBd := 0, lvlUpperBd := 1000000 , at_p := false, from_data := false, heckeBd := 100)
    // the `from_data` parameter lets us use level-raise primes we might have computed up to a larger bound.
    if from_data then
	K := Parent(f)`field;
	ZK := MaximalOrder(K);
	dd := Discriminant(K);
	if dd mod 4 eq 0 then
	    dd := dd div 4;
	end if;
	p := Characteristic(Parent(f));
	level := Level(f);
	// TODO: change this when we store data in one csv file rather than many files  
	f_file := "data/LR/" cat Sprint(-dd) cat "/" cat LMFDBLabel(level) cat "_" cat Sprint(p);
	labels := Split(Read(f_file));
	LR_primes := [LMFDBIdeal(K,str) : str in labels] cat [f[1] : f in Factorization(level*p)];
	LR_nums := [1*ZK];

	to_add := LR_primes;

	// we keep adding (up to the bound) until there's nothing left to add
	while #to_add ne 0 do 
	    new_to_add := [];
		for I in LR_nums do 
		    for J in to_add do 
			if Norm(I*J*level) le lvlUpperBd and not I*J in LR_nums then 
			    Append(~LR_nums,I*J);
			    Append(~new_to_add,J);
			end if;
		    end for;
		end for;
		to_add := new_to_add;
	end while;
	Remove(~LR_nums,1);

	nn := [Norm(u) : u in LR_nums];
	ParallelSort(~nn,~LR_nums);
    else 
	LR_nums := LevelRaiseFactors(f, Min(Floor(lvlUpperBd/Norm(Level(f))), 4000));
	// LR_nums := LevelRaisingPrimes(f);
	// LR_nums cat:= [P[1] : P in Factorization(Parent(f)`level * Characteristic(Parent(f)))];
    end if;

    if #LR_nums eq 0 then
	return "No level raising primes available";
    else
	print "Level raise factors are", [LMFDBLabel(I) : I in LR_nums];
    end if;
    
    B := Parent(f);
    level1 := Level(B);
    ZZx<x> := PolynomialRing(Integers());
    K<Kgen> := NumberField(B);
    _, levelgen := IsPrincipal(level1);
    print "Level generated by", K!levelgen, "where Kgen satisfies", MinimalPolynomial(Kgen);

    ZK := Integers(K);
    Wp := Weight(B);
    W0 := BianchiWeight(K, 0,0);
    p := Characteristic(B);
    // Only check at primes above p
    if at_p then
	LR_nums := [];
	for fac in Factorization(p*ZK) do
	    Append(~LR_nums, fac[1]);
	    Append(~LR_nums, fac[1]^2);
	end for;
	LR_nums := SortByLMFDBLabel(LR_nums);
    end if;
    
    HeckeField := HeckeField(f);
    
    // Caching is supposed to speed this up by storing eigenforms
    // see https://magma.maths.usyd.edu.au/magma/handbook/text/1784#20376
    // The main utility of this is when you're accessing the same space several times.
    // SetStoreModularForms(K, storeForms);
    // print "Factors are", [LMFDBLabel(I) : I in LR_nums];
    primes := SortByLMFDBLabel(PrimesUpTo(heckeBd, K));
    for I in LR_nums do
	level2 := I*level1;
	if Norm(level2) gt lvlUpperBd or Norm(level2) lt lvlLowerBd then
	    print "Skipping level", LMFDBLabel(I), "since not in range specified by lvlLowerBd and lvlUpperBd";
	    continue;
	end if;
	_, princ := IsPrincipal(I);
	print "Looking for lifts with level", LMFDBLabel(I), "=", K!princ, "added; new level is", LMFDBLabel(level2);

	C := BianchiCuspForms(K, level2);
	if Dimension(C) eq 0 then
	    print "Characteristic 0 space empty";
	    continue;
	end if;
	goodPrimes := [qq : qq in primes | IsCoprime(qq, level2)];
	
	// Test small Hecke operator:
	qq1 := goodPrimes[1];
	ev1 := Eigenvalue(f, qq1);
	Phi := MinimalPolynomial(HeckeOperator(C,qq1));
	if Evaluate(ChangeRing(Phi, Parent(ev1)), ev1) ne 0 then
	    print "Eigenvalue of", LMFDBLabel(qq1), "is not a root of char 0 Hecke polynomial; evaluates to", Evaluate(ChangeRing(Phi, Parent(ev1)), ev1);
	    continue;
	else
	    print "Eigenvalue of", LMFDBLabel(qq1), "is a root of char 0 Hecke polynomial --- computing newform decomposition.";
	end if;
	
	print "Computing eigenforms, this may take time";
	
	for j -> F in NewformDecomposition(NewSubspace(C)) do
	    print "Testing eigenform", j;
	    // Compute first Hecke eigenvalue to find field
	    E := Parent(HeckeEigenvalue(Eigenform(F), goodPrimes[1]));
	    if Degree(E) gt 1 then
		E<z> := Parent(HeckeEigenvalue(Eigenform(F), goodPrimes[1]));
	    else
		z := Rationals()!1;
	    end if;
	    
	    if Degree(E) lt Degree(HeckeField) then
		print "Degree of char 0 eigenvalue field is too small";
		continue;
	    end if;
	    
	    print "Eigenvalues of char 0 lift lie in", E, "of discriminant", Discriminant(Integers(E));
	    p_primes := [m[1] : m in Factorization(p*Integers(E))];
	    
	    for pp in p_primes do
		flag, prin := IsPrincipal(pp);
		Emodp_bad, phi_bad := ResidueClassField(pp);
		if flag then
		    print "Looking at reduction modulo", E!prin, "of residue degree", Degree(Emodp_bad);
		else
		    print "Looking at reduction modulo non-principal ideal above", p;
		end if;
		
		// Get better presentation of finite field than the default one:
		if Degree(Emodp_bad) gt 1 then
		    Fpx := PolynomialRing(GF(p));
		    if not exists(EmodpPol){ fac[1] : fac in Factorization(Fpx!MinimalPolynomial(z)) | Degree(fac[1]) eq Degree(Emodp_bad)} then
			print "Minimal polynomial does not have factor of correct size", [Degree(fac[1]) : fac in Factorization(Fpx!MinimalPolynomial(z))];
			continue;
		    end if;
		    Emodp<w> := ext<GF(p) | EmodpPol>;
		    assert #Emodp eq #Emodp_bad;
		    flag, Eiso := IsIsomorphic(Emodp_bad, Emodp);
		    phi := phi_bad*Eiso;
		    SetPowerPrinting(Emodp, false);
		else
		    EmodpPol := "x-1";
		    Emodp := Emodp_bad;
		    phi := phi_bad;
		end if;

		if Degree(Emodp) eq Degree(HeckeField) then
		    // this is chosen at random goddammit
		    flag, emb := IsIsomorphic(HeckeField, Emodp);
		    assert flag;
		    _, auts, _ := AutomorphismGroup(Emodp);
		elif Degree(Emodp) mod Degree(HeckeField) eq 0 then
		    Embed(HeckeField, Emodp);
		    emb := hom<HeckeField -> Emodp | x :-> Emodp!x>;
		    _, auts, _ := AutomorphismGroup(Emodp);
		else
		    print "Wrong residue degree of prime";
		    continue;
		end if;
		
		// Need to loop over automorphisms because iso is chosen at random
		for aut_no -> aut in auts do
		    wrong_ctr := 0;
		    is_wrong := false;
		    print "Testing automorphism", aut_no;
		    i := emb*aut;
		    for qq in goodPrimes do
			_, qq_gen := IsPrincipal(qq);
			
			if i(Eigenvalue(f,qq)) ne phi(HeckeEigenvalue(Eigenform(F), qq)) then
			    // This is not the right one, so move on to another level raising prime;
			    // but we will allow a couple of mismatches just in case.
			    wrong_ctr +:= 1;
			    print "Hecke eigenvalues don't agree for", LMFDBLabel(qq);
			    
			    if wrong_ctr gt 3 then
				is_wrong := true;
				wrong_ctr := 0;
				print "Eigenvalues didn't match, moving to next";
				continue aut;
			    end if;
			else
			    print "Hecke eigenvalues agree for", LMFDBLabel(qq);
			end if;
		    end for;
		    if not is_wrong then 
			print "Found correct form!";
			printf "Using prime above %o corresponding to mod p factor %o of minimal polynomial %o\n", p, EmodpPol, MinimalPolynomial(z);
			A := AssociativeArray();
			A["lift_level"] := LMFDBLabel(Level(F));
			A["Coeff_minpoly"] := Sprint(DefiningPolynomial(E));
			for pp in primes do
			    // Can only compute eigenvalues coprime to level in magma; so we pad with 0 (MAYBE: better default?)
			    A[LMFDBLabel(pp)] := IsCoprime(pp, Level(F)) select Sprint(Eltseq(HeckeEigenvalue(Eigenform(F), pp))) else "0";
			    end for;
			return A;
		    end if;

		end for;
	    end for;
	end for;
	print "---\n";
	// return inter;

    end for;
    return "None found";
end function;

