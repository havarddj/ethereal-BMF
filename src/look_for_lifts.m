// turns a line from d*_liftable.csv into its raw data so we can feed it into VerifyLMFDBLift
function UnpackLiftableString(lmfdbstr)
	ss := Split(lmfdbstr,";");
	levelLabel := ss[1];
	p := StringToInteger(ss[2]);
	eigs := [StringToInteger(u) : u in Split(ss[3][2..#ss[3]-1],",")];

	// little utility function to extract the level from a BMF label 
	function BMFLabelToLevel(foo)
		bar := foo[Index(foo,"-")+1..#foo-1];
		return bar[1..Index(bar,"-")-1];
	end function;

	liftlabels := [BMFLabelToLevel(u) : u in Split(ss[4][2..#ss[4]-1],",")];

	return levelLabel,p,eigs,liftlabels;
end function;










// tries to verify a probable lift from LMFDB data via cocycles. `zealous` option 
// checks all of them, rather than quitting once one has been found.
// `careful` option refuses to compute spaces with level more than norm 5000
function VerifyLMFDBLift(d,str : zealous := false, careful := false)
	K := QuadFld(d);
	ZK := MaximalOrder(K);

	levelLabel,p,eigs,liftLabels := UnpackLiftableString(str);

	level1 := LMFDBIdeal(K, levelLabel);

	W1 := BianchiWeight(K, 0, 0 : char := p);
	W2 := BianchiWeight(K, 0, 0);
	B1 := BianchiCohomologySpace(level1, W1);

	s := Split(Read("data/nonEis_d" cat Sprint(d) cat ".csv"),"\n")[1];
	// this cuts out just the part of the string with the labels 
	pp := s[9..#s-14];
	PP := [LMFDBIdeal(K,u) : u in Split(pp,";")];

	// this feels quite silly, having to re-egineer the string.
	fstr := levelLabel cat ";" cat Sprint(p) cat ";" cat &cat[Sprint(u) cat ";" : u in eigs];
	f := ReadClass(fstr,B1,PP);

	if zealous then
		lift_bools := [];
	end if;

	for label in liftLabels do 
		level2 := LMFDBIdeal(K, label);
		if careful and Norm(level2) gt 5000 then
			print "Level norm exceeds sensible bounds, please deactivate careful mode";
		else 

			B2 := BianchiCohomologySpace(level2, W1);
			B3 := BianchiCohomologySpace(level2, W2);

			// this is the level-raise factor 
			D := level2/level1;
			if GCD(level1,D) eq 1*ZK then 
				level_raise_f := [RaiseCocycleLevel(B1,B2,f,dd) : dd in Divisors(D)];
			else 
				level_raise_f := [RaiseCocycleLevelSlow(B1,B2,f,dd) : dd in Divisors(D)];
			end if;
			level_raise_space := sub<B2`forms | [B2`down(ff`Zvector) : ff in level_raise_f]>;

			red := ReductionModPMap(B3, B2);
			red_forms := CharacteristicZeroImage(B2,B3);

			lb := Dimension(level_raise_space meet red_forms) ge 1;

			if zealous then 
				Append(~lift_bools,lb);
			else 
				if lb then 
					return true,label;
				end if;
			end if;
		end if;

	end for;

	if zealous then 
		return lift_bools;
	else 
		return false;
	end if;

end function;


// tries to verify a lift at line number `linenum` in the file d*_liftable.csv
procedure VerifyLift(d,linenum)
	if linenum eq 1 then
		print "Table heading contained on line 1, no form to lift";
	end if;
	K := QuadFld(d);
	ZK := MaximalOrder(K);
	rr := Read("sage/d" cat Sprint(d) cat "_liftable.csv");
	lines := Split(rr);
	filename := "data/verified_d" cat Sprint(d) cat "_" cat Sprint(linenum) cat ".csv";
	SetColumns(0);

	str := lines[linenum];
	levelLabel, p, eigs := Explode(Split(str,";"));
	tt, liftLabel := VerifyLMFDBLift(d,str);
	if tt then 
		outstr := levelLabel cat ";" cat p cat ";" cat liftLabel cat ";" cat eigs;
		Write(filename,outstr);
		printf "%o: Verified lift %o\n", linenum, levelLabel cat ";" cat p cat ";" cat eigs;
	else 
		printf "Failed to verify lift %o\n", str;
	end if;
end procedure;


// checks part 2 of the conjecture for the forms in d*_liftable.csv
procedure CheckConjecture2(d : verbose := false)
	assert d in {1,2,3,7,11};
	rr := Read("sage/d" cat Sprint(d) cat "_liftable.csv");
	rr := Split(rr,"\n");

	// this skips the level 1 mod 2 system over Q(-11), which takes a very long time
	start := 2;
	if d eq 11 then 
		start := 3;
	end if;

	for i in [start..#rr] do 
		form_data := rr[i];
		print Split(form_data,";")[1..2];
		f := LoadForm_liftable(d,form_data);
		K := Parent(f)`field;
		// we gather the ideals where f lifts 
		levelLabel,p,eigs,liftLabels := UnpackLiftableString(form_data);
		
		level := LMFDBIdeal(K,levelLabel);

		lift_ideals := [LMFDBIdeal(K,u) : u in liftLabels];

		for ll in lift_ideals do 
			if verbose then 
				printf "Checking Conjecture (2) on level %o\n", LMFDBLabel(ll);
			end if;
			Q := ll/level;
			PP := [f[1] : f in Factorization(Q)];
			satisfies := true;
			for P in PP do 
				eig := Eigenvalue(f,P);
				sat := (eig^2 - (1+Norm(P))^2) eq 0 or level*p subset P;
				if not sat then 
					if not verbose then
						printf "Problem occurs at level %o, prime label %o\n", LMFDBLabel(ll), LMFDBLabel(P);
					else 
						printf "Problem occurs prime label %o\n", LMFDBLabel(P);
					end if;
					printf "a_P^2 - (1+N(P))^2 = %o\n", eig^2 - (1+Norm(P))^2;
					printf "Prime divides frak(n)*p: %o\n", level*p subset P;
					printf "Valuation of P in level raise factor: %o\n", Valuation(ll/level,P);
					printf "\n";
				end if;
				satisfies and:= sat;
			end for;
			if verbose then 
				printf "All primes in lift factor satisfy Conjecture (2): %o\n\n", satisfies;
			end if;
		end for;
		if verbose then 
			print "";
		end if;
	end for;
end procedure;



function CheckEtheralData()
	d := 1;
	K := QuadFld(d);
	ZK := MaximalOrder(K);

	rr := Read("data/nonEis_d1.csv");
	data := Split(rr,"\n");

	primeLabels := data[1][8..#data[1]-14];
	primeList := [LMFDBIdeal(K,u) : u in Split(primeLabels,";")];

	// we check each row of the file for forms wrongly marked as ethereal 
	for e in data[2..#data] do 
		ss := Split(e,";");
		level := LMFDBIdeal(K,ss[1]);
		p := StringToInteger(ss[2]);
		B := BianchiCohomologySpace(level,BianchiWeight(K,0,0 : char := p));
		B0 := BianchiCohomologySpace(level,BianchiWeight(K,0,0));
		f := ReadClass(e,B,primeList);
		if not HasEtherealEigenvalues(B0,f) then 
			print "Eigenvalue system falsely labelled ethereal";
		else 
			print "Eigenvalue system is ethereal";
		end if;
		print e;
		print "";
	end for;

end function;

